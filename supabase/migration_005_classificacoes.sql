-- Tabela classificativa
select
  competicao_nome,
  equipa,
  jogos as J,
  vitorias as V,
  empates as E,
  derrotas as D,
  gm as GM,
  gs as GS,
  diferenca_golos as DG,
  pontos as Pts
from public.classificacao_publica;

