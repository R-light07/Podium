drop policy if exists "noticias_admin_write"       on public.noticias;

create policy "noticias_public_read"
  on public.noticias for select
  using (publicada = true);

create policy "noticias_admin_read_all"
  on public.noticias for select
  using (public.is_admin());

create policy "noticias_admin_write"
  on public.noticias for all
  using (public.is_admin())
  with check (public.is_admin());

-- ----- ADMIN_USERS: cada admin vê-se a si; só admins podem adicionar outros -----
drop policy if exists "admin_users_self_read" on public.admin_users;
drop policy if exists "admin_users_manage"    on public.admin_users;

create policy "admin_users_self_read"
  on public.admin_users for select
  using (user_id = auth.uid() or public.is_admin());

create policy "admin_users_manage"
  on public.admin_users for all
  using (public.is_admin())
  with check (public.is_admin());

