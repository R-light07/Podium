-- ============================================================
-- 2. TABELA: noticias
-- ============================================================
create table if not exists public.noticias (
  id                bigint generated by default as identity primary key,
  titulo            text not null,
  slug              text unique,                             -- gerado automaticamente
  resumo            text not null,
  conteudo          text[] not null default array[]::text[],  -- array de parágrafos
  imagem_url        text,                                     -- URL da imagem no Storage
  categoria_id      bigint references public.categorias(id) on delete set null,
  autor             text not null default 'Equipa Podium',
  destaque          boolean default false,                    -- aparece no hero slider
  publicada         boolean default true,                     -- publicada vs rascunho
  data_publicacao   timestamptz default now(),
  criada_em         timestamptz default now(),
  actualizada_em    timestamptz default now(),
  criada_por        uuid references auth.users(id) on delete set null,
  views             int default 0
);

create index if not exists idx_noticias_data        on public.noticias (data_publicacao desc);
create index if not exists idx_noticias_categoria   on public.noticias (categoria_id);
create index if not exists idx_noticias_destaque    on public.noticias (destaque) where destaque = true;
create index if not exists idx_noticias_publicada   on public.noticias (publicada);
create index if not exists idx_noticias_titulo_trgm on public.noticias using gin (titulo gin_trgm_ops);
create index if not exists idx_noticias_com_imagem  on public.noticias (data_publicacao desc) where imagem_url is not null;

-- ============================================================
-- 3. TRIGGER: actualizar `actualizada_em` automaticamente
-- ============================================================
create or replace function public.handle_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.actualizada_em = now();
  return new;
end;
$$;

drop trigger if exists trg_noticias_updated on public.noticias;
create trigger trg_noticias_updated
  before update on public.noticias
  for each row execute function public.handle_updated_at();

-- ============================================================
-- 4. TRIGGER: gerar slug automaticamente a partir do título
-- ============================================================
create or replace function public.generate_slug(input_text text)
returns text
language plpgsql
immutable
as $$
begin
  return lower(
    regexp_replace(
      regexp_replace(
        unaccent(input_text),
        '[^a-zA-Z0-9\s-]', '', 'g'
      ),
      '\s+', '-', 'g'
    )
  );
end;
$$;

create or replace function public.noticia_set_slug()
returns trigger
language plpgsql
as $$
declare
  base_slug text;
  final_slug text;
  counter int := 0;
begin
  if new.slug is null or new.slug = '' then
    base_slug := public.generate_slug(new.titulo);
    final_slug := base_slug;
    -- garantir unicidade
    while exists (select 1 from public.noticias where slug = final_slug and id != coalesce(new.id, -1)) loop
      counter := counter + 1;
      final_slug := base_slug || '-' || counter;
    end loop;
    new.slug := final_slug;
  end if;
  return new;
end;
$$;

drop trigger if exists trg_noticias_slug on public.noticias;
create trigger trg_noticias_slug
  before insert or update of titulo on public.noticias
  for each row execute function public.noticia_set_slug();

