-- 7d. classificacao_publica re-criar (depende de jogos_classificacao)
drop view if exists public.classificacao_publica cascade;

create view public.classificacao_publica as
with
  jogos_expandidos as (
    select
      j.competicao_nome, j.categoria_id,
      j.equipa_casa as equipa, j.resultado_casa as gm, j.resultado_fora as gs,
      case when j.resultado_casa > j.resultado_fora then 'V'
           when j.resultado_casa < j.resultado_fora then 'D'
           else 'E' end as resultado
    from public.jogos_classificacao j
    union all
    select
      j.competicao_nome, j.categoria_id,
      j.equipa_fora as equipa, j.resultado_fora as gm, j.resultado_casa as gs,
      case when j.resultado_fora > j.resultado_casa then 'V'
           when j.resultado_fora < j.resultado_casa then 'D'
           else 'E' end as resultado
    from public.jogos_classificacao j
  ),
  agregado as (
    select
      je.competicao_nome, je.categoria_id, je.equipa,
      count(*) as jogos,
      count(*) filter (where je.resultado = 'V') as vitorias,
      count(*) filter (where je.resultado = 'E') as empates,
      count(*) filter (where je.resultado = 'D') as derrotas,
      coalesce(sum(je.gm), 0) as gm,
      coalesce(sum(je.gs), 0) as gs
    from jogos_expandidos je
    group by je.competicao_nome, je.categoria_id, je.equipa
  )
select
  c.id            as competicao_id,
  c.nome          as competicao_nome,
  c.slug          as competicao_slug,
  c.categoria_id,
  cat.slug        as categoria_slug,
  cat.nome        as categoria_nome,
  cat.emoji       as categoria_emoji,
  cat.cor         as categoria_cor,
  ag.equipa,
  ag.jogos, ag.vitorias, ag.empates, ag.derrotas,
  ag.gm, ag.gs,
  (ag.gm - ag.gs) as diferenca_golos,
  (ag.vitorias * c.pontos_vitoria
   + ag.empates  * c.pontos_empate
   + ag.derrotas * c.pontos_derrota
   + coalesce(aj.ajuste_total, 0)) as pontos,
  coalesce(aj.ajuste_total, 0) as ajuste_pontos
from public.competicoes c
left join public.categorias cat on cat.id = c.categoria_id
inner join agregado ag
  on ag.competicao_nome = c.nome
  and (ag.categoria_id = c.categoria_id or ag.categoria_id is null)
left join (
  select
    a.competicao_id,
    coalesce(eq.nome, a.equipa) as equipa_nome,
    sum(a.pontos) as ajuste_total
  from public.classificacoes_ajustes a
  left join public.equipas eq on eq.id = a.equipa_id
  group by a.competicao_id, coalesce(eq.nome, a.equipa)
) aj on aj.competicao_id = c.id and aj.equipa_nome = ag.equipa
where c.publicada = true and c.ativa = true
order by c.nome, pontos desc, diferenca_golos desc, gm desc, ag.equipa;

grant select on public.classificacao_publica to anon, authenticated;

-- 7e. top_marcadores: extrair de estatísticas usando jogador (texto OU id)
drop view if exists public.top_marcadores cascade;

create view public.top_marcadores as
with
  golos_agenda as (
    select
      e.competicao              as competicao_nome,
      e.categoria_id,
      coalesce(stat->>'jogador_nome', stat->>'jogador') as jogador_nome,
      nullif(stat->>'jogador_id', '')::bigint as jogador_id,
      stat->>'equipa'           as equipa_lado,
      case stat->>'equipa'
        when 'casa' then coalesce(eqc.nome, e.equipa_casa)
        when 'fora' then coalesce(eqf.nome, e.equipa_fora)
      end as equipa
    from public.agenda_eventos e
    left join public.equipas eqc on eqc.id = e.equipa_casa_id
    left join public.equipas eqf on eqf.id = e.equipa_fora_id
    cross join lateral jsonb_array_elements(coalesce(e.estatisticas, '[]'::jsonb)) as stat
    where e.publicado = true and e.status = 'terminado'
      and stat->>'tipo' = 'golo'
      and (stat->>'jogador' is not null or stat->>'jogador_id' is not null)
  ),
  golos_manuais as (
    select
      r.competicao              as competicao_nome,
      r.categoria_id,
      coalesce(stat->>'jogador_nome', stat->>'jogador') as jogador_nome,
      nullif(stat->>'jogador_id', '')::bigint as jogador_id,
      stat->>'equipa'           as equipa_lado,
      case stat->>'equipa'
        when 'casa' then coalesce(eqc.nome, r.equipa_casa)
        when 'fora' then coalesce(eqf.nome, r.equipa_fora)
      end as equipa
    from public.resultados r
    left join public.equipas eqc on eqc.id = r.equipa_casa_id
    left join public.equipas eqf on eqf.id = r.equipa_fora_id
    cross join lateral jsonb_array_elements(coalesce(r.estatisticas, '[]'::jsonb)) as stat
    where r.publicado = true
      and stat->>'tipo' = 'golo'
      and (stat->>'jogador' is not null or stat->>'jogador_id' is not null)
  ),
  todos as (
    select * from golos_agenda
    union all
    select * from golos_manuais
  ),
  todos_resolvidos as (
    select
      t.competicao_nome,
      t.categoria_id,
      t.jogador_id,
      coalesce(j.nome, t.jogador_nome) as jogador,
      t.equipa
    from todos t
    left join public.jogadores j on j.id = t.jogador_id
  )
select
  c.id              as competicao_id,
  c.nome            as competicao_nome,
  c.slug            as competicao_slug,
  c.categoria_id,
  cat.slug          as categoria_slug,
  cat.nome          as categoria_nome,
  cat.emoji         as categoria_emoji,
  tr.jogador,
  tr.jogador_id,
  max(tr.equipa)    as equipa,
  count(*)          as golos
from todos_resolvidos tr
inner join public.competicoes c
  on c.nome = tr.competicao_nome
  and (c.categoria_id = tr.categoria_id or tr.categoria_id is null)
left join public.categorias cat on cat.id = c.categoria_id
where c.publicada = true and c.ativa = true
  and tr.jogador is not null
group by c.id, c.nome, c.slug, c.categoria_id,
         cat.slug, cat.nome, cat.emoji,
         tr.jogador, tr.jogador_id
order by c.nome, golos desc, tr.jogador;

grant select on public.top_marcadores to anon, authenticated;

-- ============================================================
-- 8. VIEW: jogadores_actuais — jogador + equipa actual + categoria
-- ============================================================
drop view if exists public.jogadores_actuais cascade;

create view public.jogadores_actuais as
select
  j.id,
  j.nome,
  j.apelido,
  j.posicao,
  j.numero_camisola,
  j.foto_url,
  je.equipa_id,
  e.nome as equipa_nome,
  je.numero_camisola as numero_actual
from public.jogadores j
left join lateral (
  select * from public.jogadores_equipas je
  where je.jogador_id = j.id
    and (je.ate is null or je.ate >= current_date)
  order by je.desde desc nulls last
  limit 1
) je on true
left join public.equipas e on e.id = je.equipa_id;

grant select on public.jogadores_actuais to anon, authenticated;

