-- 7a. resultados_publicos com IDs e nomes via JOIN
drop view if exists public.resultados_publicos cascade;

create view public.resultados_publicos as
select
  'agenda'::text   as origem,
  e.id             as id,
  e.titulo         as titulo,
  e.competicao     as competicao,
  e.data_evento    as data_evento,
  e.local          as local,
  e.cidade         as cidade,
  e.equipa_casa_id,
  e.equipa_fora_id,
  coalesce(eqc.nome, e.equipa_casa) as equipa_casa,
  coalesce(eqf.nome, e.equipa_fora) as equipa_fora,
  e.resultado_casa,
  e.resultado_fora,
  e.mvp_id,
  coalesce(jmvp.nome, e.mvp) as mvp,
  null::text       as observacoes,
  e.estatisticas,
  e.destaque,
  c.slug           as categoria_slug,
  c.nome           as categoria_nome,
  c.emoji          as categoria_emoji,
  c.cor            as categoria_cor
from public.agenda_eventos e
left join public.categorias c    on c.id   = e.categoria_id
left join public.equipas eqc     on eqc.id = e.equipa_casa_id
left join public.equipas eqf     on eqf.id = e.equipa_fora_id
left join public.jogadores jmvp  on jmvp.id = e.mvp_id
where e.publicado = true
  and e.status = 'terminado'
  and e.resultado_casa is not null
  and e.resultado_fora is not null

union all

select
  'manual'::text as origem,
  r.id, r.titulo, r.competicao, r.data_evento, r.local, r.cidade,
  r.equipa_casa_id,
  r.equipa_fora_id,
  coalesce(eqc.nome, r.equipa_casa) as equipa_casa,
  coalesce(eqf.nome, r.equipa_fora) as equipa_fora,
  r.resultado_casa, r.resultado_fora,
  r.mvp_id,
  coalesce(jmvp.nome, r.mvp) as mvp,
  r.observacoes, r.estatisticas, r.destaque,
  c.slug as categoria_slug, c.nome as categoria_nome,
  c.emoji as categoria_emoji, c.cor as categoria_cor
from public.resultados r
left join public.categorias c    on c.id   = r.categoria_id
left join public.equipas eqc     on eqc.id = r.equipa_casa_id
left join public.equipas eqf     on eqf.id = r.equipa_fora_id
left join public.jogadores jmvp  on jmvp.id = r.mvp_id
where r.publicado = true

order by data_evento desc;

