-- 6e. MIGRAR JOGADORES DE TEXTO PARA TABELA
-- ============================================================
-- Inserir jogadores únicos do MVP + estatísticas
do $$
declare
  e_record record;
  r_record record;
  stat jsonb;
  jogador_nome text;
  jogador_id_var bigint;
begin
  -- MVP da agenda
  for e_record in select id, mvp from public.agenda_eventos
    where mvp is not null and trim(mvp) <> '' and mvp_id is null
  loop
    insert into public.jogadores (nome) values (trim(e_record.mvp))
    on conflict do nothing;
    select id into jogador_id_var from public.jogadores
      where lower(nome) = lower(trim(e_record.mvp)) limit 1;
    update public.agenda_eventos set mvp_id = jogador_id_var where id = e_record.id;
  end loop;

  -- MVP dos resultados
  for r_record in select id, mvp from public.resultados
    where mvp is not null and trim(mvp) <> '' and mvp_id is null
  loop
    insert into public.jogadores (nome) values (trim(r_record.mvp))
    on conflict do nothing;
    select id into jogador_id_var from public.jogadores
      where lower(nome) = lower(trim(r_record.mvp)) limit 1;
    update public.resultados set mvp_id = jogador_id_var where id = r_record.id;
  end loop;

  -- Jogadores das estatísticas (golos)
  for r_record in select estatisticas from public.resultados where estatisticas is not null
  loop
    for stat in select jsonb_array_elements(r_record.estatisticas)
    loop
      jogador_nome := stat->>'jogador';
      if jogador_nome is not null and trim(jogador_nome) <> '' then
        insert into public.jogadores (nome) values (trim(jogador_nome))
        on conflict do nothing;
      end if;
    end loop;
  end loop;

  for e_record in select estatisticas from public.agenda_eventos where estatisticas is not null
  loop
    for stat in select jsonb_array_elements(e_record.estatisticas)
    loop
      jogador_nome := stat->>'jogador';
      if jogador_nome is not null and trim(jogador_nome) <> '' then
        insert into public.jogadores (nome) values (trim(jogador_nome))
        on conflict do nothing;
      end if;
    end loop;
  end loop;
end $$;

-- ============================================================
-- 6f. INFERIR jogadores_equipas a partir das estatísticas
--    (jogador X marcou pela equipa casa Y → vínculo X-Y)
-- ============================================================
with golos_extraidos as (
  select
    trim(stat->>'jogador') as jogador_nome,
    case stat->>'equipa'
      when 'casa' then r.equipa_casa_id
      when 'fora' then r.equipa_fora_id
    end as equipa_id
  from public.resultados r
  cross join lateral jsonb_array_elements(coalesce(r.estatisticas, '[]'::jsonb)) as stat
  where stat->>'tipo' = 'golo'
    and stat->>'jogador' is not null
    and trim(stat->>'jogador') <> ''
)
insert into public.jogadores_equipas (jogador_id, equipa_id)
select distinct j.id, ge.equipa_id
from golos_extraidos ge
join public.jogadores j on lower(j.nome) = lower(ge.jogador_nome)
where ge.equipa_id is not null
  and not exists (
    select 1 from public.jogadores_equipas je
    where je.jogador_id = j.id and je.equipa_id = ge.equipa_id
  );

