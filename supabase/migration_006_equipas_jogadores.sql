-- ============================================================
-- PODIUM — MIGRATION 006: Equipas e Jogadores
-- ============================================================
-- Cria entidades reutilizáveis para equipas e jogadores.
-- Migra os dados existentes (texto livre → IDs) e actualiza
-- todas as views/tabelas dependentes.
--
-- COMO CORRER:
--   Supabase Dashboard → SQL Editor → New query → colar tudo → Run
--
-- IDEMPOTENTE (com cuidado): pode correr múltiplas vezes; a
-- migração de dados textuais é guardada por checks de existência.
--
-- Pré-requisitos: migrations 003, 004 e 005 já corridas.
-- ============================================================

-- ============================================================
-- 1. TABELA: equipas (globais — uma equipa pode jogar várias modalidades)
-- ============================================================
create table if not exists public.equipas (
  id              bigint generated by default as identity primary key,
  nome            text not null,
  slug            text unique not null,
  cidade          text,
  fundada_em      int,                                    -- ano de fundação
  cores           text,                                   -- ex: "azul-amarelo"
  emblema_url     text,                                   -- URL do logo no Storage
  observacoes     text,
  criada_em       timestamptz default now(),
  actualizada_em  timestamptz default now()
);

create index if not exists idx_equipas_nome on public.equipas (lower(nome));
create unique index if not exists uniq_equipas_nome_lower
  on public.equipas (lower(nome));

drop trigger if exists trg_equipas_updated on public.equipas;
create trigger trg_equipas_updated
  before update on public.equipas
  for each row execute function public.handle_updated_at();

-- ============================================================
-- 2. TABELA: jogadores
-- ============================================================
create table if not exists public.jogadores (
  id              bigint generated by default as identity primary key,
  nome            text not null,
  apelido         text,                                   -- nome de jogo (ex: "Geny")
  data_nascimento date,
  posicao         text,                                   -- ex: "Avançado", "Base", "Líbero"
  numero_camisola int,                                    -- nº actual (referência rápida)
  foto_url        text,
  observacoes     text,
  criada_em       timestamptz default now(),
  actualizada_em  timestamptz default now()
);

create index if not exists idx_jogadores_nome on public.jogadores (lower(nome));

drop trigger if exists trg_jogadores_updated on public.jogadores;
create trigger trg_jogadores_updated
  before update on public.jogadores
  for each row execute function public.handle_updated_at();

-- ============================================================
-- 3. TABELA: jogadores_equipas (relação N:N com histórico)
-- ============================================================
create table if not exists public.jogadores_equipas (
  id              bigint generated by default as identity primary key,
  jogador_id      bigint not null references public.jogadores(id) on delete cascade,
  equipa_id       bigint not null references public.equipas(id) on delete cascade,
  desde           date,                                   -- data início (opcional)
  ate             date,                                   -- data fim (null = actual)
  numero_camisola int,
  observacoes     text,
  criada_em       timestamptz default now()
);

create index if not exists idx_je_jogador on public.jogadores_equipas (jogador_id);
create index if not exists idx_je_equipa  on public.jogadores_equipas (equipa_id);
create index if not exists idx_je_actual  on public.jogadores_equipas (jogador_id) where ate is null;

-- ============================================================
-- 4. ROW LEVEL SECURITY
-- ============================================================
alter table public.equipas              enable row level security;
alter table public.jogadores            enable row level security;
alter table public.jogadores_equipas    enable row level security;

