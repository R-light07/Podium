select distinct
  trim(equipa) as nome,
  lower(regexp_replace(
    regexp_replace(
      translate(trim(equipa),
        'áàâãäåÁÀÂÃÄÅéèêëÉÈÊËíìîïÍÌÎÏóòôõöÓÒÔÕÖúùûüÚÙÛÜçÇñÑ',
        'aaaaaaAAAAAAeeeeEEEEiiiiIIIIoooooOOOOOuuuuUUUUcCnN'),
      '[^a-zA-Z0-9\s-]', '', 'g'),
    '\s+', '-', 'g'
  )) as slug
from (
  select equipa_casa as equipa from public.agenda_eventos where equipa_casa is not null
  union
  select equipa_fora from public.agenda_eventos where equipa_fora is not null
  union
  select equipa_casa from public.resultados where equipa_casa is not null
  union
  select equipa_fora from public.resultados where equipa_fora is not null
  union
  select equipa from public.classificacoes_ajustes where equipa is not null
) as fontes
where trim(equipa) <> ''
on conflict do nothing;

